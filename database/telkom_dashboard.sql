CREATE TABLE IF NOT EXISTS `kuadran_summaries` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `bulan` VARCHAR(10) NOT NULL COMMENT 'Jul, Aug, Sep, Oct, Nov, Dec',
  `period` VARCHAR(10) NOT NULL DEFAULT '' COMMENT 'YYYYMM, contoh: 202607, 202608',
  `telda` VARCHAR(100) NOT NULL COMMENT 'Region / Telda',
  `unit` VARCHAR(50) NOT NULL COMMENT 'Segment: Business, Enterprise, Government',
  `kw_awal` VARCHAR(10) NOT NULL DEFAULT '' COMMENT '1..4, NEW, atau kosong untuk bulan dasar',
  `kw_akhir` TINYINT UNSIGNED NOT NULL COMMENT 'Kuadran bulan berjalan (1..4)',
  `jumlah` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Jumlah pelanggan',
  `created_at` TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_kuadran_summary` (`bulan`, `telda`, `unit`, `kw_awal`, `kw_akhir`),
  KEY `idx_bulan` (`bulan`),
  KEY `idx_telda` (`telda`),
  KEY `idx_unit` (`unit`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

